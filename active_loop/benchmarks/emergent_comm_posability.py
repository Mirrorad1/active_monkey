"""A costed moving-resource harness for the Exp 278 posability test.

The resource identity is generated by the environment and changes every round;
the only temporal regularity available to a policy is that the next identity is
not the previous one.  The oracle is deliberately provided the current identity
and is charged for using that signal.  ``oracle_net_reward`` is a SHARED/KIN DYAD
payoff: forager success minus scout signal cost, under the honest incentive
assumption that the scout benefits through shared fitness.  This does not model
selection for an individual unrelated scout.  This is a posability instrument,
not a language or emergent-communication demonstration.
"""
from __future__ import annotations

from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass

import numpy as np


HISTORY_TOLERANCE = 0.03
ORACLE_ADVANTAGE_FLOOR = 0.70
ORACLE_NET_FLOOR = 0.80
STATIC_TRAIL_FLOOR = 0.95


@dataclass(frozen=True)
class PosabilityConfig:
    n_sites: int = 8
    rounds: int = 2000
    signal_cost: float = 0.05

    def __post_init__(self) -> None:
        if self.n_sites < 2:
            raise ValueError("n_sites must be at least 2")
        if self.rounds < 1:
            raise ValueError("rounds must be positive")
        if not 0.0 < self.signal_cost <= 1.0:
            raise ValueError("signal_cost must be in (0, 1]")


@dataclass(frozen=True)
class SeedResult:
    seed: int
    chance: float
    history_ceiling: float
    solo_success: float
    trail_success: float
    history_optimal_success: float
    shuffled_signal_success: float
    oracle_success: float
    oracle_net_reward: float
    static_trail_success: float

    def to_dict(self) -> dict[str, float | int]:
        return asdict(self)


@dataclass(frozen=True)
class GateResult:
    baselines_fail: bool
    oracle_advantage: bool
    costed_oracle_viable: bool
    static_control_live: bool
    verdict: str

    def to_dict(self) -> dict[str, bool | str]:
        return asdict(self)


def _rng(seed: int, arm: int) -> np.random.Generator:
    """Return an arm-local stream derived only from ``(seed, arm)``."""
    return np.random.default_rng(np.random.SeedSequence([int(seed), int(arm)]))


def resource_path(seed: int, config: PosabilityConfig, *, static: bool = False) -> tuple[int, ...]:
    """Generate a reproducible resource path with no adjacent repeats.

    A static path is a positive control: one site is repeated for every round.
    """
    rng = _rng(seed, 0)
    first = int(rng.integers(config.n_sites))
    if static:
        return (first,) * config.rounds

    path = [first]
    sites = np.arange(config.n_sites)
    for _ in range(1, config.rounds):
        previous = path[-1]
        choices = sites[sites != previous]
        path.append(int(rng.choice(choices)))
    return tuple(path)


def _successes(predictions: list[int], path: tuple[int, ...]) -> float:
    return sum(prediction == actual for prediction, actual in zip(predictions, path)) / len(path)


def _trail_predictions(path: tuple[int, ...], rng: np.random.Generator) -> list[int]:
    """The trail-following policy shared by moving and static evaluations."""
    n_sites = max(path) + 1
    return [
        int(rng.integers(n_sites)) if index == 0 else path[index - 1]
        for index in range(len(path))
    ]


def _encode_site(site: int, n_sites: int) -> int:
    """Gifted scout encoder: each site gets a distinct token identity."""
    return int(n_sites + site)


def _decode_token(token: int, token_to_site: dict[int, int]) -> int:
    """Gifted token-to-site decoder used by the oracle."""
    return int(token_to_site[token])


def _oracle_predictions(path: tuple[int, ...], n_sites: int) -> list[int]:
    """Encode, deliver, and decode each current resource identity."""
    token_to_site = {_encode_site(site, n_sites): site for site in range(n_sites)}
    delivered_tokens = [_encode_site(site, n_sites) for site in path]
    return [_decode_token(token, token_to_site) for token in delivered_tokens]


def _evaluate(seed: int, path: tuple[int, ...], config: PosabilityConfig) -> SeedResult:
    n_sites = config.n_sites
    rounds = config.rounds
    sites = np.arange(n_sites)

    solo_rng = _rng(seed, 1)
    trail_rng = _rng(seed, 2)
    history_rng = _rng(seed, 3)
    shuffled_rng = _rng(seed, 4)

    solo = [int(solo_rng.integers(n_sites)) for _ in path]

    trail = _trail_predictions(path, trail_rng)

    history_optimal: list[int] = []
    for index, actual in enumerate(path):
        if index == 0:
            history_optimal.append(int(history_rng.integers(n_sites)))
        else:
            choices = sites[sites != path[index - 1]]
            history_optimal.append(int(history_rng.choice(choices)))

    # IID tokens are independent of the current resource, so this control is
    # information-free rather than merely temporally misaligned.
    shuffled_signal = [int(shuffled_rng.integers(n_sites)) for _ in path]

    static_path = resource_path(seed, config, static=True)
    # Score only rounds for which the previous resource has been exposed.  The
    # first round is intentionally excluded from this positive-control rate.
    static_predictions = _trail_predictions(static_path, _rng(seed, 2))
    static_trail = _successes(static_predictions[1:], static_path[1:]) if rounds > 1 else 0.0
    oracle_predictions = _oracle_predictions(path, n_sites)
    oracle_success = _successes(oracle_predictions, path)

    return SeedResult(
        seed=int(seed),
        chance=1.0 / n_sites,
        history_ceiling=1.0 / (n_sites - 1),
        solo_success=_successes(solo, path),
        trail_success=_successes(trail, path),
        history_optimal_success=_successes(history_optimal, path),
        shuffled_signal_success=_successes(shuffled_signal, path),
        oracle_success=oracle_success,
        # Shared/KIN DYAD payoff: forager success minus scout signal cost.
        oracle_net_reward=oracle_success - config.signal_cost,
        static_trail_success=float(static_trail),
    )


def run_seed(seed: int, config: PosabilityConfig, *, static: bool = False) -> SeedResult:
    """Evaluate all policies for one seed against one shared resource path."""
    return _evaluate(seed, resource_path(seed, config, static=static), config)


def _run_seed_job(job: tuple[int, PosabilityConfig]) -> SeedResult:
    """Picklable ProcessPool job; all randomness remains seed/arm-derived."""
    seed, config = job
    return run_seed(seed, config)


def run_batch(
    seeds: tuple[int, ...],
    config: PosabilityConfig,
    *,
    parallel: bool = True,
    max_workers: int | None = None,
) -> tuple[SeedResult, ...]:
    """Evaluate an independent seed ensemble, returned in seed order."""
    if not parallel or len(seeds) < 2:
        return tuple(run_seed(seed, config) for seed in seeds)

    worker_count = min(max_workers or len(seeds), len(seeds))
    with ProcessPoolExecutor(max_workers=worker_count) as executor:
        rows = tuple(executor.map(_run_seed_job, ((seed, config) for seed in seeds)))
    return tuple(sorted(rows, key=lambda row: row.seed))


def grade_posability(rows: tuple[SeedResult, ...], config: PosabilityConfig) -> GateResult:
    """Apply every predeclared conjunct; one failed seed fails its conjunct."""
    if not rows:
        return GateResult(False, False, False, False, "CANT_POSE")

    baselines_fail = all(
        max(
            row.solo_success,
            row.trail_success,
            row.history_optimal_success,
            row.shuffled_signal_success,
        )
        <= row.history_ceiling + HISTORY_TOLERANCE
        for row in rows
    )
    max_baselines = [
        max(
            row.solo_success,
            row.trail_success,
            row.history_optimal_success,
            row.shuffled_signal_success,
        )
        for row in rows
    ]
    oracle_advantage = all(
        row.oracle_net_reward - baseline >= ORACLE_ADVANTAGE_FLOOR
        for row, baseline in zip(rows, max_baselines)
    )
    costed_oracle_viable = all(row.oracle_net_reward >= ORACLE_NET_FLOOR for row in rows)
    static_control_live = all(row.static_trail_success >= STATIC_TRAIL_FLOOR for row in rows)
    verdict = (
        "POSABLE"
        if all((baselines_fail, oracle_advantage, costed_oracle_viable, static_control_live))
        else "CANT_POSE"
    )
    return GateResult(
        baselines_fail=baselines_fail,
        oracle_advantage=oracle_advantage,
        costed_oracle_viable=costed_oracle_viable,
        static_control_live=static_control_live,
        verdict=verdict,
    )
